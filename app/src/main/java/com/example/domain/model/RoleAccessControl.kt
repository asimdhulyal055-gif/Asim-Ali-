        roleModules[role] ?: setOf(AppModule.DASHBOARD, AppModule.USER_PROFILE)

    fun activePhase1Modules(role: UserRole): List<AppModule> =
        allowedModules(role).filter { it.isImplementedInCurrentPhase }

    fun roadmapModules(role: UserRole): List<AppModule> =
        allowedModules(role).filterNot { it.isImplementedInCurrentPhase }

